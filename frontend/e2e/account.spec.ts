import { test, expect } from "@playwright/test";
import { createHmac } from "node:crypto";
import { appendFileSync } from "node:fs";
function otp(secret: string, delta = 0) {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  const bits = [...secret.replace(/=/g, "")].map((c) => alphabet.indexOf(c).toString(2).padStart(5, "0")).join("");
  const bytes = Buffer.from(bits.match(/.{8}/g)!.map((b) => parseInt(b, 2)));
  const counter = Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000) + delta));
  const digest = createHmac("sha1", bytes).update(counter).digest();
  return ((digest.readUInt32BE(digest[19] & 15) & 0x7fffffff) % 1000000).toString().padStart(6, "0");
}
test("cadastro, alteração de senha e ativação do autenticador completam o fluxo", async ({ page }, info) => {
  test.skip(info.project.name !== "desktop", "Conta descartável: demais formulários já cobertos nas três larguras");
  const api = process.env.E2E_API_URL ?? "http://localhost:8000";
  if (!["localhost", "127.0.0.1"].includes(new URL(api).hostname)) throw new Error("Somente local");
  const username = "flow" + Date.now().toString().slice(-12);
  const email = username + "@example.com";
  await page.goto("/register");
  await page.getByLabel("Nome de usuário", { exact: true }).fill(username);
  await page.getByLabel("E-mail", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill("Capmar-Cadastro@123");
  await page.getByLabel("Confirmar senha", { exact: true }).fill("Outra-Senha@123");
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await expect(page.getByText("As senhas não coincidem.")).toBeVisible();
  await page.getByLabel("Confirmar senha", { exact: true }).fill("Capmar-Cadastro@123");
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await expect(page).toHaveURL(/\/feed$/);
  const me = await (await page.request.get(api + "/auth/me")).json();
  appendFileSync("../docs/thiago/e2e-created-users.jsonl", JSON.stringify({ user_id: me.user_id, username, email }) + "\n");
  await page.goto("/seguranca");
  await page.locator("summary").filter({hasText:"Alterar senha"}).click();
  const form = page.getByRole("form", { name: "Alterar senha", exact: true });
  await form.getByLabel("Senha atual", { exact: true }).fill("Capmar-Cadastro@123");
  await form.getByLabel("Nova senha", { exact: true }).fill("Capmar-Alterada@123");
  await form.getByRole("button", { name: "Alterar senha e encerrar sessões" }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel("E-mail", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill("Capmar-Alterada@123");
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/feed$/);
  await page.goto("/seguranca");
  await page.locator("summary").filter({hasText:"Autenticador em duas etapas"}).click();
  const setup = page.locator("section").filter({ has: page.getByRole("heading", { name: "Autenticador em duas etapas" }) });
  await setup.getByLabel("Senha atual", { exact: true }).fill("Capmar-Alterada@123");
  await setup.getByRole("button", { name: "Configurar autenticador" }).click();
  const secret = (await setup.locator("code").innerText()).trim();
  await setup.getByLabel("Código do autenticador", { exact: true }).fill(otp(secret, -1));
  await setup.getByRole("button", { name: "Confirmar autenticador" }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel("E-mail", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill("Capmar-Alterada@123");
  await page.getByLabel("Uso um aplicativo autenticador").check();
  await page.getByLabel("Código do autenticador (se ativado)").fill(otp(secret));
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/feed$/);
  await page.goto("/seguranca");
  await page.locator("summary").filter({hasText:"Autenticador em duas etapas"}).click();
  await expect(page.getByText("MFA está ativo. O login exige senha e código do autenticador.")).toBeVisible();
});
