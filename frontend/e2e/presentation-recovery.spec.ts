    const encoded = await dialog.getByRole("img").getAttribute("src");
    const png = PNG.sync.read(Buffer.from(encoded!.split(",")[1], "base64"));
    expect(jsQR(new Uint8ClampedArray(png.data), png.width, png.height)?.data).toBe(base + "/projeto/" + id);
    await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
    await dialog.getByRole("button", { name: "Copiar link", exact: true }).click();
