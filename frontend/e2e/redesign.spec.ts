import { test, expect } from "@playwright/test";
const api=process.env.E2E_API_URL??"http://localhost:8000";
const base=process.env.E2E_BASE_URL??"http://localhost:3001";
if(![api,base].every(u=>["localhost","127.0.0.1"].includes(new URL(u).hostname)))throw Error("Somente local");
test("nova conversa, busca local, teclado e navegação de segurança",async({page},info)=>{
  expect((await page.request.post(api+"/auth/login",{headers:{Origin:base,"X-CSRF-Protection":"1"},data:{email:"e2e_alice@example.com",password:"Capmar-E2E@123"}})).status()).toBe(200);
  await page.goto("/chat");
  await page.getByRole("button",{name:"Nova mensagem",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"Nova mensagem",exact:true});
  await dialog.getByLabel("Nome ou usuário").fill("@e2e_bob");
  await dialog.getByRole("button",{name:"Buscar",exact:true}).click();
  await dialog.getByRole("button").filter({hasText:"@e2e_bob"}).click();
  const room=page.getByRole("region",{name:"Conversa",exact:true});
  await expect(room.getByRole("heading",{name:"@e2e_bob",exact:true})).toBeVisible();
  const message="QA composição "+info.project.name+" "+Date.now();
  await room.getByRole("textbox",{name:"Mensagem",exact:true}).fill(message);
  await room.getByRole("textbox",{name:"Mensagem",exact:true}).press("Shift+Enter");
  await expect(room.getByRole("textbox",{name:"Mensagem",exact:true})).toHaveValue(message+"\n");
  await room.getByRole("textbox",{name:"Mensagem",exact:true}).press("Enter");
  await expect(room.getByText(message,{exact:true})).toBeVisible();
  await expect(room.getByRole("textbox",{name:"Mensagem",exact:true})).toHaveValue("");
  if(info.project.name.startsWith("mobile"))await room.getByRole("link",{name:"Voltar para conversas"}).click();
  await page.getByLabel("Buscar nesta lista").fill("@e2e_bob");
  await expect(page.getByRole("button",{name:"@e2e_bob",exact:true})).toBeVisible();
  await page.getByLabel("Buscar nesta lista").fill("zzzznenhum");
  await expect(page.getByRole("button",{name:"@e2e_bob",exact:true})).toHaveCount(0);
  await page.goto("/seguranca");
  await expect(page.getByRole("heading",{name:"Segurança da conta",exact:true})).toBeVisible();
  const password=page.getByRole("form",{name:"Alterar senha",exact:true});
  await expect(password).toBeHidden();
  await page.locator("summary").filter({hasText:"Alterar senha"}).click();
  await expect(password.getByLabel("Nova senha",{exact:true})).toBeVisible();
  await page.locator("summary").filter({hasText:"Autenticador em duas etapas"}).click();
  await expect(page.getByRole("button",{name:"Configurar autenticador",exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.goto("/feed");
  const search=page.getByRole("search");
  await search.getByRole("textbox",{name:"Buscar projetos"}).fill("Feira Criativa");
  await search.getByRole("button",{name:"Buscar",exact:true}).click();
  await expect(page).toHaveURL(/\/home\?q=Feira/);
  await expect(page.getByRole("heading",{name:"Feira Criativa de Maricá",exact:true})).toBeVisible();
});
